def q(v):
    """Quote a Python value as a MySQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (dict, list)):
        v = json.dumps(v, ensure_ascii=False)
    s = str(v)
    for a, b in (("\\", "\\\\"), ("'", "\\'"), ("\n", "\\n"), ("\r", "\\r"), ("\x00", "\\0"), ("\x1a", "\\Z")):
        s = s.replace(a, b)
    return "'" + s + "'"


def ts(epoch):
    return q(time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(epoch))) if epoch else "CURRENT_TIMESTAMP"


def rows(table, cols, values, upsert=None):
    if not values:
        return ""
    body = ",\n".join("  (" + ", ".join(v) + ")" for v in values)
    tail = ""
    if upsert:
        tail = " AS new\nON DUPLICATE KEY UPDATE " + ", ".join(f"{c} = new.{c}" for c in upsert)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n{body}{tail};\n\n"


def loc_id(name):
    return f"(SELECT id FROM locations WHERE name = {q(name)})"


# ----------------------------------------------------------------------------- seed

def build_seed():
    from server import DEFAULT_SETTINGS  # the app's defaults
    out = ["-- =============================================================================",
           "--  UNIQO - 03_seed_config.sql : default site configuration + Design Lobby catalogue",
           "--  GENERATED by db/mysql/uniqo_mysql.py seed - edit lobby_catalog.py, then regenerate.",
           "--  Safe to re-run: existing rows are updated in place.",
           "-- =============================================================================",
           "USE uniqo;", "SET NAMES utf8mb4;", ""]
    settings = dict(DEFAULT_SETTINGS, lobby={"enabled": True, "show_estimate": True})
    out.append(rows("site_settings", ["setting_key", "setting_value", "description"],
                    [[q(k), q(json.dumps(v, ensure_ascii=False)), q(SETTING_NOTES.get(k))] for k, v in settings.items()],
                    upsert=["setting_value", "description"]))
    out.append(rows("locations", ["name", "is_default", "sort_order"],
                    [[q(n), q(n == settings["default_location"]), str(i)] for i, n in enumerate(settings["locations"])],
                    upsert=["is_default", "sort_order"]))
    out.append(rows("lobby_silhouettes", ["silhouette_key", "label", "description", "base_price", "meters", "making_days", "allows_belt", "allows_dupatta", "sort_order"],
                    [[q(s["key"]), q(s["label"]), q(s["desc"]), str(s["base"]), str(s["meters"]), str(s["days"]),
                      q(s["key"] in BELT_OK), q(s["key"] != "saree"), str(i)] for i, s in enumerate(LC.SILHOUETTES)],
                    upsert=["label", "description", "base_price", "meters", "making_days", "allows_belt", "allows_dupatta", "sort_order"]))
    out.append(rows("lobby_fabrics", ["fabric_key", "label", "description", "tag", "gsm", "care", "luxury", "rate_per_meter",
                                      "stat_comfort", "stat_drape", "stat_stretch", "stat_breathability", "stat_formality",
                                      "render_texture", "render_sheen", "render_sheer", "sort_order"],
                    [[q(f["key"]), q(f["label"]), q(f["desc"]), q(f["tag"]), q(f["gsm"]), q(f["care"]), str(f["luxury"]), str(f["rate"]),
                      *[str(f["stats"][k]) for k in ("comfort", "drape", "stretch", "breathability", "formality")],
                      q(RENDER[f["key"]][0]), str(RENDER[f["key"]][1]), str(RENDER[f["key"]][2]), str(i)]
                     for i, f in enumerate(LC.FABRICS)],
                    upsert=["label", "description", "tag", "gsm", "care", "luxury", "rate_per_meter", "stat_comfort", "stat_drape",
                            "stat_stretch", "stat_breathability", "stat_formality", "render_texture", "render_sheen", "render_sheer", "sort_order"]))
    out.append("DELETE FROM lobby_fabric_best_for;\n")
    out.append(rows("lobby_fabric_best_for", ["fabric_key", "silhouette_key"],
                    [[q(f["key"]), q(s)] for f in LC.FABRICS for s in f["best"]]))
    out.append(rows("lobby_necklines", ["neckline_key", "label", "sort_order"],
                    [[q(n["key"]), q(n["label"]), str(i)] for i, n in enumerate(LC.NECKLINES)], upsert=["label", "sort_order"]))
    out.append(rows("lobby_sleeves", ["sleeve_key", "label", "extra_meters", "sort_order"],
                    [[q(s["key"]), q(s["label"]), str(s["meters"]), str(i)] for i, s in enumerate(LC.SLEEVES)],
                    upsert=["label", "extra_meters", "sort_order"]))
    out.append(rows("lobby_lengths", ["length_key", "label", "meter_factor", "sort_order"],
                    [[q(l["key"]), q(l["label"]), str(l["factor"]), str(i)] for i, l in enumerate(LC.LENGTHS)],
                    upsert=["label", "meter_factor", "sort_order"]))
    out.append(rows("lobby_embellishments", ["emb_key", "label", "description", "price", "making_days", "sort_order"],
                    [[q(e["key"]), q(e["label"]), q(e["desc"]), str(e["price"]), str(e["days"]), str(i)] for i, e in enumerate(LC.EMBELLISHMENTS)],
                    upsert=["label", "description", "price", "making_days", "sort_order"]))
    out.append(rows("lobby_palette", ["palette", "name", "hex", "sort_order"],
                    [[q("main"), q(n), q(h), str(i)] for i, (n, h) in enumerate(LC.COLORS)] +
                    [[q("trim"), q(n), q(h), str(i)] for i, (n, h) in enumerate(LC.ACCENTS)], upsert=["name", "sort_order"]))
    out.append(rows("lobby_skin_tones", ["value", "label", "sort_order"],
                    [[q(s), q("Atelier mannequin" if s == "mannequin" else f"Skin tone {i + 1}"), str(i)] for i, s in enumerate(LC.SKINS)],
                    upsert=["label", "sort_order"]))
    labels = {"dupatta_meters": ("Dupatta fabric", "meters"), "belt": ("Waist belt", "rupees"),
              "lining": ("Full lining", "rupees"), "pockets": ("Hidden pockets", "rupees")}
    out.append(rows("lobby_extras", ["extra_key", "label", "value", "unit"],
                    [[q(k), q(labels[k][0]), str(v), q(labels[k][1])] for k, v in LC.EXTRAS.items()], upsert=["label", "value", "unit"]))
    return "\n".join(out)


# ----------------------------------------------------------------------------- export

def build_export(db_path):
    if not os.path.isfile(db_path):
        sys.exit(f"SQLite database not found: {db_path}\nStart the website once (python server.py) to create it.")
    con = sqlite3.connect(db_path)
    con.row_factory = sqlite3.Row
    settings = {r["key"]: json.loads(r["value"]) for r in con.execute("SELECT key, value FROM settings")}

    out = ["-- =============================================================================",
           "--  UNIQO - 05_data.sql : full data export from the running website",
           f"--  GENERATED {time.strftime('%Y-%m-%d %H:%M')} from {os.path.basename(db_path)}",
           "--  WARNING: replaces all business data (designs, orders, feedback, looks, customers).",
           "-- =============================================================================",
           "USE uniqo;", "SET NAMES utf8mb4;", "SET FOREIGN_KEY_CHECKS = 0;", "START TRANSACTION;", ""]
    for t in ("saved_looks", "customer_sessions", "customer_accounts",
              "look_embellishments", "looks", "order_addons", "orders", "customers", "feedback", "design_editions",
              "design_hotspots", "design_occasions", "design_addons", "design_sizes", "design_colors", "design_images", "designs"):
        out.append(f"DELETE FROM {t};")
    out.append("")

    # --- configuration overrides made in the admin panel
    sset = [[q(k), q(json.dumps(v, ensure_ascii=False))] for k, v in settings.items() if k not in ("admin_auth", "seeded")]
    if "lobby" in settings:
        sset = [r for r in sset if r[0] != q("lobby")]
        lb = settings["lobby"]
        sset.append([q("lobby"), q(json.dumps({"enabled": lb.get("enabled", True), "show_estimate": lb.get("show_estimate", True)}))])
    out.append(rows("site_settings", ["setting_key", "setting_value"], sset, upsert=["setting_value"]))

    # every city referenced anywhere must exist before it is used as a foreign key
    cities = list(settings.get("locations") or [])
    designs = con.execute("SELECT * FROM designs ORDER BY id").fetchall()
    for d in designs:
        cities += [e["location"] for e in json.loads(d["data"]).get("editions", [])]
    cities += [r[0] for r in con.execute("SELECT DISTINCT location FROM orders")]
    if con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='looks'").fetchone():
        cities += [r[0] for r in con.execute("SELECT DISTINCT location FROM looks")]
    seen = []
    for c in cities:
        if c not in seen:
            seen.append(c)
    default = settings.get("default_location") or (seen[0] if seen else None)
    out.append("UPDATE locations SET is_default = 0;")
    out.append(rows("locations", ["name", "is_active", "is_default", "sort_order"],
                    [[q(c), q(c in (settings.get("locations") or seen)), q(c == default), str(i)] for i, c in enumerate(seen)],
                    upsert=["is_active", "is_default", "sort_order"]))

    # lobby price / on-off overrides
    lob = settings.get("lobby") or {}
    for group, table, keycol, pricecol, src in (("fabrics", "lobby_fabrics", "fabric_key", "rate_per_meter", "rate"),
                                                ("silhouettes", "lobby_silhouettes", "silhouette_key", "base_price", "base"),
                                                ("embellishments", "lobby_embellishments", "emb_key", "price", "price")):
        for k, o in (lob.get(group) or {}).items():
            out.append(f"UPDATE {table} SET is_enabled = {q(bool(o.get('enabled', True)))}"
                       + (f", {pricecol} = {int(o[src])}" if src in o else "") + f" WHERE {keycol} = {q(k)};")
    for k, v in (lob.get("extras") or {}).items():
        out.append(f"UPDATE lobby_extras SET value = {int(v)} WHERE extra_key = {q(k)};")
    out.append("")

    # --- admin login (keeps the current password)
    if "admin_auth" in settings:
        a = settings["admin_auth"]
        out.append(rows("admin_users", ["username", "password_salt", "password_hash"], [[q("admin"), q(a["salt"]), q(a["hash"])]],
                        upsert=["password_salt", "password_hash"]))

    # --- designs and their children
    spec_cols = ["fabric", "lining", "weight", "fit", "neckline", "sleeve", "length", "closure", "embellishment", "care", "making_days"]
    feel_cols = ["comfort", "drape", "stretch", "breathability", "formality"]
    drows, imgs, cols, sizes, addons, occ, spots, eds = [], [], [], [], [], [], [], []
    for r in designs:
        d = json.loads(r["data"])
        did = str(r["id"])
        drows.append([did, q(r["slug"]), q(d["name"]), q(d.get("category", "Couture")), q(d.get("badge", "")), q(d.get("tagline", "")),
                      q(d.get("story", "")), q(r["status"]), str(r["sort_order"]), q(bool(d.get("featured"))), str(int(d.get("price", 0))),
                      q(d.get("price_mode", "default")), q(bool(d.get("made_to_measure"))), str(int(d.get("mtm_delta", 0))),
                      *[q((d.get("specs") or {}).get(k, "")) for k in spec_cols],
                      *[str(int((d.get("feel") or {}).get(k, 3))) for k in feel_cols],
                      str(r["views"]), str(r["reveals"]), ts(r["created_at"]), ts(r["updated_at"])])
        imgs += [[did, q(u), q(d["name"]), str(i)] for i, u in enumerate(d.get("images", []))]
        cols += [[did, q(c["name"]), q(c["hex"]), q(c.get("image") or None), str(int(c.get("delta", 0))), str(i)] for i, c in enumerate(d.get("colors", []))]
        sizes += [[did, q(s), str(i)] for i, s in enumerate(d.get("sizes", []))]
        addons += [[did, q(a["name"]), q(a.get("desc", "")), str(int(a.get("delta", 0))), str(i)] for i, a in enumerate(d.get("addons", []))]
        occ += [[did, q(o)] for o in d.get("occasions", [])]
        spots += [[did, str(i), str(h["x"]), str(h["y"]), q(h["title"]), q(h.get("text", ""))] for i, h in enumerate(d.get("hotspots", []))]
        eds += [[did, loc_id(e["location"]), str(int(e["limit"]))] for e in d.get("editions", [])]
    out.append(rows("designs", ["id", "slug", "name", "category", "badge", "tagline", "story", "status", "sort_order", "featured", "base_price",
                                "price_mode", "made_to_measure", "mtm_delta", *["spec_" + k for k in spec_cols],
                                *["feel_" + k for k in feel_cols], "views", "reveals", "created_at", "updated_at"], drows))
    out.append(rows("design_images", ["design_id", "url", "alt_text", "position"], imgs))
    out.append(rows("design_colors", ["design_id", "name", "hex", "image_url", "price_delta", "position"], cols))
    out.append(rows("design_sizes", ["design_id", "size_label", "position"], sizes))
    out.append(rows("design_addons", ["design_id", "name", "description", "price_delta", "position"], addons))
    out.append(rows("design_occasions", ["design_id", "occasion"], occ))
    out.append(rows("design_hotspots", ["design_id", "position", "x_pct", "y_pct", "title", "body"], spots))
    out.append(rows("design_editions", ["design_id", "location_id", "piece_limit"], eds))

    # --- customers (one per mobile, latest details win) + orders
    orders = con.execute("SELECT * FROM orders ORDER BY id").fetchall()
    custs = {}
    for o in orders:
        custs[o["mobile"]] = [q(o["mobile"]), q(o["name"]), q(o["address"]), q(o["pincode"]), loc_id(o["location"])]
    looks = []
    if con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name='looks'").fetchone():
        looks = con.execute("SELECT * FROM looks ORDER BY id").fetchall()
        for k in looks:
            custs.setdefault(k["mobile"], [q(k["mobile"]), q(k["name"]), "NULL", "NULL", loc_id(k["location"])])
    has = lambda t: bool(con.execute("SELECT name FROM sqlite_master WHERE type='table' AND name=?", (t,)).fetchone())
    accounts = con.execute("SELECT * FROM accounts ORDER BY created_at").fetchall() if has("accounts") else []
    for a in accounts:
        custs.setdefault(a["mobile"], [q(a["mobile"]), q(a["name"]), "NULL", "NULL", "NULL"])
    out.append(rows("customers", ["mobile", "name", "address", "pincode", "location_id"], list(custs.values())))

    # customer accounts + saved designs (sessions are not migrated: customers simply sign in again)
    out.append(rows("customer_accounts", ["customer_id", "mobile", "display_name", "pin_salt", "pin_hash", "failed_pins", "created_at", "updated_at"],
                    [[f"(SELECT id FROM customers WHERE mobile = {q(a['mobile'])})", q(a["mobile"]), q(a["name"]), q(a["pin_salt"]),
                      q(a["pin_hash"]), str(a["failed"]), ts(a["created_at"]), ts(a["updated_at"])] for a in accounts]))
    saved = con.execute("SELECT * FROM saved_looks ORDER BY id").fetchall() if has("saved_looks") else []
    out.append(rows("saved_looks", ["id", "account_id", "title", "look_json", "created_at", "updated_at"],
                    [[str(s["id"]), f"(SELECT id FROM customer_accounts WHERE mobile = {q(s['mobile'])})", q(s["title"]), q(s["look"]),
                      ts(s["created_at"]), ts(s["updated_at"])] for s in saved]))

    design_ids = {r["id"] for r in designs}
    orow, oadd = [], []
    for o in orders:
        c = json.loads(o["config"])
        orow.append([str(o["id"]), q(o["ref"]), f"(SELECT id FROM customers WHERE mobile = {q(o['mobile'])})",
                     str(o["design_id"]) if o["design_id"] in design_ids else "NULL", q(o["design_name"]), loc_id(o["location"]),
                     q(o["location"]), str(o["edition_no"]), str(o["edition_limit"]), q(o["name"]), q(o["mobile"]), q(o["address"]),
                     q(o["pincode"]), q(c.get("color", "")), q(c.get("size", "")),
                     q(c.get("measurements")) if any((c.get("measurements") or {}).values()) else "NULL",
                     str(o["total"]), q(o["notes"] or ""), q(o["status"]), ts(o["created_at"]), ts(o["updated_at"])])
        oadd += [[str(o["id"]), q(a), "0"] for a in c.get("addons", [])]
    out.append(rows("orders", ["id", "ref", "customer_id", "design_id", "design_name", "location_id", "location_name", "edition_no",
                               "edition_limit", "customer_name", "mobile", "address", "pincode", "color_name", "size_label",
                               "measurements", "total", "notes", "status", "created_at", "updated_at"], orow))
    # add-on prices at order time were not stored separately in SQLite; take today's catalogue price
    out.append(rows("order_addons", ["order_id", "addon_name", "price"], oadd))
    if oadd:
        out.append("UPDATE order_addons oa JOIN orders o ON o.id = oa.order_id JOIN design_addons a ON a.design_id = o.design_id AND a.name = oa.addon_name\n"
                   "SET oa.price = a.price_delta;\n")

    # --- feedback
    fb = con.execute("SELECT * FROM feedback ORDER BY id").fetchall()
    out.append(rows("feedback", ["id", "design_id", "client_id", "reaction", "comment", "created_at"],
                    [[str(f["id"]), str(f["design_id"]), q(f["client_id"]), q(f["reaction"]), q(f["comment"] or ""), ts(f["created_at"])]
                     for f in fb if f["design_id"] in design_ids]))

    # --- design-lobby commissions
    lrow, lemb = [], []
    for k in looks:
        L = json.loads(k["look"])
        lrow.append([str(k["id"]), q(k["ref"]), f"(SELECT id FROM customers WHERE mobile = {q(k['mobile'])})", q(k["name"]), q(k["mobile"]),
                     loc_id(k["location"]), q(L["sil"]), q(L["fab"]), q(L["neck"]), q(L["slv"]), q(L["len"]), q(L["col"]), q(L["acc"]),
                     q(L.get("dup", "none")), q(bool(L.get("belt"))), q(bool(L.get("lining"))), q(bool(L.get("pockets"))),
                     q(L.get("skin", "#c98e66")), q(L), str(k["estimate"]), q(k["notes"] or ""), q(k["status"]),
                     ts(k["created_at"]), ts(k["updated_at"])])
        lemb += [[str(k["id"]), q(e)] for e in L.get("emb", [])]
    out.append(rows("looks", ["id", "ref", "customer_id", "customer_name", "mobile", "location_id", "silhouette_key", "fabric_key",
                              "neckline_key", "sleeve_key", "length_key", "main_hex", "trim_hex", "dupatta", "has_belt", "has_lining",
                              "has_pockets", "skin", "look_json", "estimate", "notes", "status", "created_at", "updated_at"], lrow))
    out.append(rows("look_embellishments", ["look_id", "emb_key"], lemb))

    out += ["COMMIT;", "SET FOREIGN_KEY_CHECKS = 1;", "",
            f"-- exported: {len(designs)} designs, {len(orders)} orders, {len(fb)} feedback, {len(looks)} looks, "
            f"{len(custs)} customers, {len(accounts)} accounts, {len(saved)} saved designs"]
    con.close()
    return "\n".join(out), (len(designs), len(orders), len(fb), len(looks), len(custs), len(accounts), len(saved))


def admin_sql(user):
    pw = os.environ.get("UNIQO_ADMIN_PASSWORD") or getpass.getpass(f"New password for admin '{user}': ")
    if len(pw) < 8:
        sys.exit("Password must be at least 8 characters.")
    salt = secrets.token_hex(16)
    digest = hashlib.pbkdf2_hmac("sha256", pw.encode(), bytes.fromhex(salt), 200_000).hex()
    return (f"USE uniqo;\nINSERT INTO admin_users (username, password_salt, password_hash) VALUES ({q(user)}, {q(salt)}, {q(digest)}) AS new\n"
            "ON DUPLICATE KEY UPDATE password_salt = new.password_salt, password_hash = new.password_hash, is_active = 1;\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("seed")
    s.add_argument("--out", default=os.path.join(HERE, "03_seed_config.sql"))
    e = sub.add_parser("export")
    e.add_argument("--sqlite", default=os.path.join(os.environ.get("UNIQO_DATA_DIR") or os.path.join(ROOT, "data"), "uniqo.db"))
    e.add_argument("--out", default=os.path.join(HERE, "05_data.sql"))
    a = sub.add_parser("admin-sql")
    a.add_argument("--user", default="admin")
    args = ap.parse_args()

    if args.cmd == "seed":
        with open(args.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(build_seed())
        print(f"Wrote {args.out}")
    elif args.cmd == "export":
        sql, counts = build_export(args.sqlite)
        with open(args.out, "w", encoding="utf-8", newline="\n") as f:
            f.write(sql)
        print(f"Wrote {args.out}: {counts[0]} designs, {counts[1]} orders, {counts[2]} feedback, {counts[3]} looks, "
              f"{counts[4]} customers, {counts[5]} accounts, {counts[6]} saved designs")
    else:
        sys.stdout.write(admin_sql(args.user))


if __name__ == "__main__":
    main()
